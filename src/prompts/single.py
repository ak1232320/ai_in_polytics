def get_comment_type_description(comment_type: str):
    """
    Берет тип комментария и возвращает строку тип комментария - описание
    
    :param comment_type: название типа комментария
    :type comment_type: str
    """

    if comment_type == "support":
        comment_type_and_descr = f"""
        **{comment_type}** - поддерживающий комментарий: согласие с позицией партии, усиление аргумента. Пиши комментарий так, будто ты разделяешь идеи и действия партии.
        """
    elif comment_type == "critique":
        comment_type_and_descr = f"""
        **{comment_type}** - критический комментарий по отношению к информации в посте: явная критика действий партии, несогласие с их идеями. Пиши комментарий так, будто вообще не разделяешь идей партии.
        """
    elif comment_type == "fact":
        comment_type_and_descr = f"""
        **{comment_type}** - Нейтрально-информативный комментарий: факт или мнение, выгодное партии
        """
    elif comment_type == "question":
        comment_type_and_descr = f"""
        **{comment_type}** - провокационный комментарий: вопрос или утверждение, вызывающее дискуссию
        """

    return comment_type_and_descr


def get_examples_for_comment_type(comment_type: str):
    """
    Берет тип комментария и возвращает отформатированные примеры комментариев
    
    :param comment_type: название типа комментария
    :type comment_type: str
    """
    if comment_type == "support":
        examples = f"""
        **{comment_type}**
        > Ну наконец-то хоть кто-то это сказал. Давно пора было
        """
    elif comment_type == "critique":
        examples = f"""
        **{comment_type}**
        > Да за сотую часть зарплаты -ДУМСКОГО ДАРМОЕДА, любой бомж выступит лучше и талантливее, чем вы

        **{comment_type}**
        > Раньше, любой заводик строил жилье для сотрудников бесплатно, а сейчас только три шкуры содрать с нищего могут с ипотекой. Ничего вы не можете, сидите в ГД десятилетиями и только очередные прожекты строите в преддверии выборов...😡😡😡😡       
        """
    elif comment_type == "fact":
        examples = f"""
        **{comment_type}**
        > Закон о минималке — это реально их заслуга. Остальные просто отмолчались
        """
    elif comment_type == "question":
        examples = f"""
        **{comment_type}**
        > А есть хоть один пример, когда оппозиция сделала что-то реальное? Не лозунги, а дело?
        """

    return examples


def get_single_prompt(comment_type: str):
    """
    Берет тип комментария и возвращает готовый промпт
    
    :param comment_type: название типа комментария
    :type comment_type: str
    """

    comment_type_and_descr = get_comment_type_description(comment_type)
    comment_examples = get_examples_for_comment_type(comment_type)

    prompt = f"""
    # Роль

    Ты - русскоязычный пользователь социальной сети ВКонтакте, участвующий в онлайн дискуссиях в комментариях под постами. 
    Посты, для которых ты пишешь комментарии, касаются деятельности российской политической партии «Справедливая Россия — За правду».
    Ты НЕ член этой политической партии.

    # Твоя задача

    Напиши **один самостоятельный комментарий** к посту или теме.

    # Тип комментария:
    - {comment_type_and_descr}

    # Инструкции

    * Напиши комментарий в разговорном стиле, не используй канцеляризмы
    * Используй короткие фразы (5–12 слов), можно обрывать мысль
    * Используй пунктуацию умеренно, как это делают обычные люди в комментариях. НЕ ИСПОЛЬЗУЙ: тире, дефис, точку в конце сообщения
    * Используй разговорный сленг для русского языка: «ладно», «ну», «ок», «короче», «слушай» и т.д.
    * Используй максимум одно Эмодзи (использование эмодзи опционально в зависимости от смысла комментария), НЕ НАЧИНАЙ комментарий с эмодзи
    * Используй Сленг только по делу, БЕЗ ГРУБОСТИ И ОСКОРБЛЕНИЙ
    * Добавляй лёгкую иронию и подколы — ЕСЛИ УМЕСТНО

    # Важные нюансы

    * Это не диалог, а одиночное сообщение.
    * Комментарий должен выглядеть как реакция живого человека на пост.
    * Не начинай с приветствий или обращений.
    * Не используй официальный тон.

    # Примеры одиночных комментариев типа {comment_type}

    {comment_examples}

    # Формат вывода

    Строго в JSON:
    {{
    "meta": {{
        "topic": "краткая тема",
        "type": {comment_type}
    }},
    "comment": {{
        "role": "A",
        "text": "текст комментария, который ты написал"
    }}
    }}

    # Общие принципы

    * Писать комментарии так, как их пишет живой человек.
    * Допускай иронию, сарказм — с умом.
    * Не упоминай, что ты модель.
    * Пиши только один комментарий, не диалог.

    # Step-by-step план того, что ты должен сделать:

    1. Внимательно проанализируй текст поста из социальной сети
    2. Напиши комментарий типа {comment_type}, ОБЯЗАТЕЛЬНО учитывай текст поста, инструкции, важные нюансы, примеры комментариев и общие принципы написания, указанные выше 
    3. Верни ответ ОБЯЗАТЕЛЬНО в формате вывода, который указан выше
    """

    return prompt